import { execFile } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { Readable } from 'node:stream'
import { promisify } from 'node:util'
import { fileURLToPath } from 'node:url'
import { parseNomismaRdf } from '../../server/ingestion/nomisma-local-parser.ts'

const exec = promisify(execFile)
const repo = fileURLToPath(new URL('../../', import.meta.url))
const output = new URL('../src/shared/nomisma.generated.ts', import.meta.url)
const selection = {
  ruler: [
    ['augustus','Augustus','Octavian','Caesar Augustus'], ['tiberius','Tiberius'], ['gaius','Caligula','Gaius','Gaius Caligula'],
    ['claudius','Claudius'], ['nero','Nero'], ['galba','Galba'], ['otho','Otho'], ['vitellius','Vitellius'],
    ['vespasian','Vespasian'], ['titus','Titus'], ['domitian','Domitian'], ['nerva','Nerva'], ['trajan','Trajan','Traianus'],
    ['hadrian','Hadrian','Hadrianus'], ['marcus_aurelius','Marcus Aurelius'], ['constantine_i','Constantine I','Constantine the Great']
  ],
  mint: [['rome','Rome','Roma','Roman mint'], ['antiocheia_syria','Antioch','Antioch on the Orontes']],
  denomination: [['aureus','Aureus'], ['denarius','Denarius'], ['sestertius','Sestertius'], ['as','As'], ['dupondius','Dupondius'],
    ['tetradrachm','Tetradrachm']],
  metal: [['ar','Silver','AR'], ['av','Gold','AV'], ['ae','Bronze','AE']]
}
const terms = await Promise.all(Object.entries(selection).flatMap(([kind, rows]) =>
  rows.map(async ([id, display, ...localAliases]) => {
    const path = 'nomisma-data/id/' + id + '.rdf'
    const { stdout } = await exec('git', ['show', 'HEAD:' + path], { cwd: repo, windowsHide: true, maxBuffer: 2_000_000 })
    const record = await parseNomismaRdf(Readable.from([stdout]), path)
    if (!record || record.type !== kind || record.uri !== 'http://nomisma.org/id/' + id) {
      throw new Error('The selected RDF must establish a ' + kind + ' with ID ' + id)
    }
    const aliases = [...new Set([display, record.label, ...localAliases, ...record.alternateLabels])]
      .filter(label => label && label !== display && label.length <= 180)
      .slice(0, 12)
    return {id, kind, label:display, sourceLabel:record.label, aliases, source:record.uri.replace(/^http:/, 'https:')}
  })
))
const generated = '// Generated by scripts/build-nomisma.mjs from NumisGraph\'s bundled Nomisma.org RDF.\n' +
  '// Nomisma.org concepts are attributed under CC BY.\n' +
  'export const referenceTerms = ' + JSON.stringify(terms, null, 2) + ' as const\n'
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')).replaceAll('\r\n','\n') !== generated) {
    throw new Error('Generated Nomisma data is out of date. Run npm run refs:build.')
  }
} else {
  await writeFile(output, generated, 'utf8')
}
console.log('Verified ' + terms.length + ' source-backed Nomisma terms.')
