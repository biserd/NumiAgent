test('Public blog opens from the mobile header and links back from an article',async({page})=>{
  const hydrationErrors:string[]=[]
  page.on('console',event=>{
    if (/hydration/i.test(event.text()) && ['error','warning'].includes(event.type())) hydrationErrors.push(event.text())
  })
  await page.setViewportSize({width:320,height:720})
  await page.goto(server.url)
  await page.getByRole('navigation',{name:'Main',exact:true}).getByRole('link',{name:'Blog',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Coin and banknote collecting guides',exact:true})).toBeVisible()
  await expect(page.locator('.post-grid article')).toHaveCount(6)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
  await page.getByRole('link',{name:'How to photograph coins and banknotes for your catalog'}).click()
  await expect(page.getByRole('heading',{name:'Review before you save',exact:true})).toBeVisible()
  await page.getByRole('link',{name:'identify a Roman coin',exact:true}).click()
  await expect(page.getByRole('heading',{name:'How to identify a Roman coin from its legend and mint mark'})).toBeVisible()
  await page.getByRole('navigation',{name:'Breadcrumb'}).getByRole('link',{name:'Coin and banknote collecting guides'}).click()
  await expect(page.getByRole('link',{name:'Subscribe via RSS'})).toHaveAttribute('href','/blog/rss.xml')
  expect(hydrationErrors).toEqual([])
})
